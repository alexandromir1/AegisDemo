export function getIncidentById(id: string): FireEvent | undefined {
  const seed = incidents.find((i) => i.id === id)
  return seed ? hydrateWithEvidence(structuredClone(seed)) : undefined
}

export function cloneIncidents(): FireEvent[] {
  return structuredClone(incidents).map(hydrateWithEvidence)
}
