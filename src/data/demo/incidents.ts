function ring(
  lat: number,
  lng: number,
  radiusDeg: number,
  points = 24,
): [number, number][] {
  const coords: [number, number][] = []
  for (let i = 0; i <= points; i++) {
    const angle = (i / points) * Math.PI * 2
    coords.push([
      lat + Math.sin(angle) * radiusDeg * 0.75,
      lng + Math.cos(angle) * radiusDeg,
    ])
  }
  return coords
}

